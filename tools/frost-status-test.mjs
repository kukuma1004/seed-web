import assert from 'node:assert/strict';
import {applyFrostContact,FROST_SHATTER_HITS} from '../src/frost-status.js';

const foe={slow:0};
assert.equal(FROST_SHATTER_HITS,5);
assert.deepEqual(applyFrostContact(foe,{now:1}),{first:true,shatter:false,stacks:1,bonus:0});
assert.equal(foe.slow,1.3);
for(let i=2;i<5;i++)assert.deepEqual(applyFrostContact(foe,{now:1+(i-1)*.2}),{first:false,shatter:false,stacks:i,bonus:0});
assert.deepEqual(applyFrostContact(foe,{now:1.8}),{first:false,shatter:true,stacks:5,bonus:.9});
assert.equal(foe.frostLock,.55);
assert.equal(applyFrostContact(foe,{now:2}).shatter,false);
assert.equal(applyFrostContact(foe,{now:4}).stacks,1,'the shell expires without continuous hits');
const boss={slow:0};
for(let i=0;i<4;i++)assert.equal(applyFrostContact(boss,{now:4+i*.2,boss:true}).bonus,0);
assert.equal(applyFrostContact(boss,{now:4.8,boss:true}).bonus,1.25);
assert.equal(boss.frostLock,undefined);
const sustained={slow:0};let added=0;
for(let i=0;i<50;i++)added+=applyFrostContact(sustained,{now:i*.22,boss:true}).bonus;
assert.ok(added/50>=.17&&added/50<=.28,`sustained frost boss bonus ${added/50} should reward focus without snowballing`);
console.log('Five-hit frost shell, boss shatter, expiry and ordinary lock passed.');
