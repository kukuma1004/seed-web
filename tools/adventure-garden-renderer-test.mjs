const assets={garden:{complete:false,naturalWidth:1254},arena:{complete:false,naturalWidth:1536}};
const p=createAdventureGardenPainter(ctx,assets,()=>new Path2D());
const R={nodes:[{x:8,y:19,role:'start'}],paths:[],landmarks:[]};
